// Generates cli/init/unicode_data.mbt: the Unicode character properties and
// case mappings of the Rust standard library that the `init` command uses
// (through heck 0.5.0 and `str::to_lowercase`), taken from the toolchain
// that builds the pinned upstream CLI:
//
//   rustc +1.97.1 -O tools/oracle/gen_rust_unicode.rs -o _build/gen_rust_unicode
//   _build/gen_rust_unicode > cli/init/unicode_data.mbt
//   moon fmt   # then restore the files it should not touch
//
// `Case_Ignorable` and `Cased` are not public in std; they are recovered from
// `str::to_lowercase`'s Final_Sigma rule (`map_uppercase_sigma`):
//   "{c}Σ" ends in ς  iff  !Case_Ignorable(c) && Cased(c)
//   "Ä{c}Σ" ends in ς iff  Case_Ignorable(c) || Cased(c)
// `Cased` is only observable (and only needed) for characters that are not
// case-ignorable.
use std::fmt::Write;

fn all_chars() -> impl Iterator<Item = char> {
    (0u32..=0x10FFFF).filter_map(char::from_u32)
}

fn ranges(name: &str, doc: &str, pred: impl Fn(char) -> bool) {
    let mut pairs: Vec<(u32, u32)> = Vec::new();
    for c in all_chars() {
        let v = c as u32;
        if pred(c) {
            match pairs.last_mut() {
                // Surrogates are not chars: a range may span them.
                Some((_, hi)) if *hi + 1 == v || (*hi == 0xD7FF && v == 0xE000) => *hi = v,
                _ => pairs.push((v, v)),
            }
        }
    }
    println!("///|\n/// {doc}\nlet {name} : FixedArray[UInt] = [");
    let mut line = String::new();
    for (lo, hi) in pairs {
        let item = format!("0x{lo:X}, 0x{hi:X},");
        if line.len() + item.len() + 1 > 78 {
            println!("  {}", line.trim_end());
            line.clear();
        }
        line.push_str(&item);
        line.push(' ');
    }
    if !line.is_empty() {
        println!("  {}", line.trim_end());
    }
    println!("]\n");
}

fn mapping(name: &str, doc: &str, map: impl Fn(char) -> String) {
    let mut keys = String::new();
    let mut values = String::new();
    for c in all_chars() {
        let m = map(c);
        if m != c.to_string() {
            writeln!(keys, "  0x{:X},", c as u32).unwrap();
            let mut lit = String::new();
            for d in m.chars() {
                write!(lit, "\\u{{{:X}}}", d as u32).unwrap();
            }
            writeln!(values, "  \"{lit}\",").unwrap();
        }
    }
    println!("///|\n/// {doc} (keys)\nlet {name}_keys : FixedArray[UInt] = [\n{keys}]\n");
    println!("///|\n/// {doc} (values)\nlet {name}_values : FixedArray[String] = [\n{values}]\n");
}

fn sigma_final(s: &str) -> bool {
    s.to_lowercase().ends_with('ς')
}

fn main() {
    println!("// Generated by tools/oracle/gen_rust_unicode.rs from Rust 1.97.1's");
    println!("// `core::unicode` tables (formatted by `moon fmt`). Do not edit.\n");
    ranges(
        "alphanumeric_table",
        "`char::is_alphanumeric` (Alphabetic or Numeric), as inclusive ranges.",
        |c| c.is_alphanumeric(),
    );
    ranges(
        "lowercase_table",
        "`char::is_lowercase` (Lowercase), as inclusive ranges.",
        |c| c.is_lowercase(),
    );
    ranges(
        "uppercase_table",
        "`char::is_uppercase` (Uppercase), as inclusive ranges.",
        |c| c.is_uppercase(),
    );
    ranges(
        "case_ignorable_table",
        "`Case_Ignorable`, as inclusive ranges.",
        |c| !sigma_final(&format!("{c}Σ")) && sigma_final(&format!("Ä{c}Σ")),
    );
    ranges(
        "cased_not_case_ignorable_table",
        "`Cased` characters that are not `Case_Ignorable`, as inclusive ranges.",
        |c| sigma_final(&format!("{c}Σ")),
    );
    mapping(
        "to_lowercase",
        "`char::to_lowercase` where it differs from the character",
        |c| c.to_lowercase().collect(),
    );
    mapping(
        "to_uppercase",
        "`char::to_uppercase` where it differs from the character",
        |c| c.to_uppercase().collect(),
    );
}
