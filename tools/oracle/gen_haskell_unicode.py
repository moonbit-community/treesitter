"""Generate scanners/haskell_unicode.mbt from tree-sitter-haskell's src/unicode.h.

Usage:
  python3 tools/oracle/gen_haskell_unicode.py [UNICODE_H]

UNICODE_H defaults to the pinned checkout's src/unicode.h
(.repos/grammars/haskell, tree-sitter-haskell v0.24.1). The header consists of
bitmaps (`static uint8_t bitmap_<name>[]`), their `min`/`max` code points, one
lookup function per bitmap and one dispatch function per character class. The
script checks that every function has exactly the shape below and reproduces
the bitmaps byte for byte as `Bytes` literals.

It also checks that no lookup reachable through a dispatch function indexes
past the end of its bitmap (which would be an out-of-bounds read in C).
Development-only; format the generated file afterwards with
`moonfmt -w scanners/haskell_unicode.mbt` (the committed file is its output).
"""
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]


def default_header():
    common = Path(subprocess.check_output(
        ['git', 'rev-parse', '--path-format=absolute', '--git-common-dir'], cwd=ROOT, text=True).strip()).parent
    return common / '.repos/grammars/haskell/src/unicode.h'


path = Path(sys.argv[1]) if len(sys.argv) > 1 else default_header()
text = path.read_text()

bitmaps = {}
for m in re.finditer(r'static uint8_t bitmap_(\w+)\[\] = \{([^}]*)\};', text):
    values = [int(v, 0) for v in m.group(2).replace('\n', '').split(',') if v.strip()]
    assert all(0 <= v <= 255 for v in values)
    bitmaps[m.group(1)] = values
bounds = {}
for m in re.finditer(r'static int32_t bitmap_(\w+)_(min|max)_codepoint = (\d+);', text):
    bounds.setdefault(m.group(1), {})[m.group(2)] = int(m.group(3))
assert set(bounds) == set(bitmaps)

# Per-bitmap lookups.
LOOKUP = ('static bool is_{n}_char(int32_t c) {{\n'
          '  int32_t offset = c - bitmap_{n}_min_codepoint;\n'
          '  return (bitmap_{n}[offset >> 3] & (1u << (offset & 7))) > 0;\n'
          '}}\n')
CHECKED = ('static bool is_{n}_char(int32_t c) {{\n'
           '  if (c < bitmap_{n}_min_codepoint || c > bitmap_{n}_max_codepoint) return false;\n'
           '  int32_t offset = c - bitmap_{n}_min_codepoint;\n'
           '  return (bitmap_{n}[offset >> 3] & (1u << (offset & 7))) > 0;\n'
           '}}\n')
lookups = {}
for name in bitmaps:
    if LOOKUP.format(n=name) in text:
        lookups[name] = 'plain'
    elif CHECKED.format(n=name) in text:
        lookups[name] = 'checked'
    else:
        raise SystemExit(f'unexpected lookup function for {name}')

# Dispatch functions: a chain of `c < min ? false : c <= max ? is_X_char(c) :`.
classes = {}
for m in re.finditer(r'static bool is_(\w+)_char\(int32_t c\) \{\n  return\n((?:    .*\n)*?)    false;\n\}\n', text):
    body = m.group(2).splitlines()
    assert len(body) % 2 == 0
    parts = []
    for k in range(0, len(body), 2):
        a = re.fullmatch(r'    c < bitmap_(\w+)_min_codepoint \? false :', body[k])
        b = re.fullmatch(r'    c <= bitmap_(\w+)_max_codepoint \? is_(\w+)_char\(c\) :', body[k + 1])
        assert a and b and a.group(1) == b.group(1) == b.group(2), body[k:k + 2]
        assert lookups[a.group(1)] == 'plain'
        parts.append(a.group(1))
    classes[m.group(1)] = parts
used = {p for ps in classes.values() for p in ps}
standalone = [n for n in bitmaps if lookups[n] == 'checked']
assert used | set(standalone) == set(bitmaps) and not (used & set(standalone))
# Every function in the header is accounted for.
assert text.count('static bool ') == len(bitmaps) + len(classes)

# Out-of-bounds check: the largest index a lookup can compute is
# (max - min) >> 3.
for name, values in bitmaps.items():
    lo, hi = bounds[name]['min'], bounds[name]['max']
    assert lo <= hi
    need = ((hi - lo) >> 3) + 1
    if need > len(values):
        raise SystemExit(f'bitmap_{name}: lookups up to index {need - 1}, but it has {len(values)} bytes')


def literal(values):
    return 'b"' + ''.join(f'\\x{v:02x}' for v in values) + '"'


out = ['// Port of tree-sitter-haskell src/unicode.h (v0.24.1).',
       '// Generated by tools/oracle/gen_haskell_unicode.py. Do not edit.',
       '// tree-sitter-haskell is distributed under the MIT license (see NOTICE).',
       '']
for name, values in bitmaps.items():
    lo, hi = bounds[name]['min'], bounds[name]['max']
    out += ['///|', f'let hs_bitmap_{name} : Bytes = {literal(values)}', '',
            '///|', f'const HS_BITMAP_{name.upper()}_MIN_CODEPOINT : Int32 = {lo}', '',
            '///|', f'const HS_BITMAP_{name.upper()}_MAX_CODEPOINT : Int32 = {hi}', '']
    out += ['///|', f'fn hs_is_{name}_char(c : Int32) -> Bool {{']
    if lookups[name] == 'checked':
        out += [f'  if c < HS_BITMAP_{name.upper()}_MIN_CODEPOINT || c > HS_BITMAP_{name.upper()}_MAX_CODEPOINT {{',
                '    return false', '  }']
    out += [f'  let offset = c - HS_BITMAP_{name.upper()}_MIN_CODEPOINT',
            f'  (hs_bitmap_{name}[offset >> 3].to_int() & (1 << (offset & 7))) > 0',
            '}', '']
for cls, parts in classes.items():
    out += ['///|', f'fn hs_is_{cls}_char(c : Int32) -> Bool {{']
    for p in parts:
        out += [f'  if c < HS_BITMAP_{p.upper()}_MIN_CODEPOINT {{', '    return false', '  }',
                f'  if c <= HS_BITMAP_{p.upper()}_MAX_CODEPOINT {{', f'    return hs_is_{p}_char(c)', '  }']
    out += ['  false', '}', '']

target = ROOT / 'scanners/haskell_unicode.mbt'
target.write_text('\n'.join(out).rstrip('\n') + '\n')
print(f'wrote {target}: {len(bitmaps)} bitmaps, {sum(map(len, bitmaps.values()))} bytes, classes {list(classes)}')
