#!/usr/bin/env python3
"""Embed tree-sitter crates/cli/src/templates/* verbatim into
cli/init/templates.mbt (the `include_str!` constants of init.rs).

Usage: python3 tools/next/gen_init_templates.py [<pinned checkout>]

Each template becomes a `#|` multiline string. A template that ends with a
newline gets a final empty `#|` line; templates containing characters that a
`#|` line cannot hold (CR, other control characters except tab) are emitted
as escaped string literals instead.
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PINNED = sys.argv[1] if len(sys.argv) > 1 else "/Users/dii/git/treesitter/.repos/ts-pinned"
TEMPLATES = os.path.join(PINNED, "crates/cli/src/templates")
OUT = os.path.join(ROOT, "cli/init/templates.mbt")

# (MoonBit name, template file), in init.rs order.
ENTRIES = [
    ("grammar_js_template", "grammar.js"),
    ("package_json_template", "package.json"),
    ("gitignore_template", "gitignore"),
    ("gitattributes_template", "gitattributes"),
    ("editorconfig_template", ".editorconfig"),
    ("lib_rs_template", "lib.rs"),
    ("build_rs_template", "build.rs"),
    ("cargo_toml_template", "_cargo.toml"),
    ("index_js_template", "index.js"),
    ("index_d_ts_template", "index.d.ts"),
    ("js_binding_cc_template", "js-binding.cc"),
    ("binding_gyp_template", "binding.gyp"),
    ("binding_test_js_template", "binding_test.js"),
    ("makefile_template", "makefile"),
    ("cmakelists_txt_template", "cmakelists.cmake"),
    ("parser_name_h_template", "PARSER_NAME.h"),
    ("parser_name_pc_in_template", "PARSER_NAME.pc.in"),
    ("go_mod_template", "go.mod"),
    ("binding_go_template", "binding.go"),
    ("binding_test_go_template", "binding_test.go"),
    ("setup_py_template", "setup.py"),
    ("init_py_template", "__init__.py"),
    ("init_pyi_template", "__init__.pyi"),
    ("pyproject_toml_template", "pyproject.toml"),
    ("py_binding_c_template", "py-binding.c"),
    ("test_binding_py_template", "test_binding.py"),
    ("package_swift_template", "package.swift"),
    ("tests_swift_template", "tests.swift"),
    ("pom_xml_template", "pom.xml"),
    ("binding_java_template", "binding.java"),
    ("test_java_template", "test.java"),
    ("build_zig_template", "build.zig"),
    ("build_zig_zon_template", "build.zig.zon"),
    ("root_zig_template", "root.zig"),
    ("test_zig_template", "test.zig"),
]


def escaped(text):
    out = []
    for c in text:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
        elif c == "\r":
            out.append("\\r")
        elif c == "\t":
            out.append("\\t")
        elif ord(c) < 0x20:
            out.append("\\u{%x}" % ord(c))
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def emit(name, file):
    text = open(os.path.join(TEMPLATES, file), "rb").read().decode("utf-8")
    lines = [f"///|", f"/// `templates/{file}`.", f"let {name} : String ="]
    if any((ord(c) < 0x20 and c not in "\t\n") for c in text) or text == "":
        lines.append("  " + escaped(text))
    else:
        parts = text.split("\n")
        # A trailing newline yields a final empty part, i.e. a final `#|`.
        for part in parts:
            lines.append(("  #|" + part).rstrip(" ") if part == "" else "  #|" + part)
    return "\n".join(lines) + "\n"


def main():
    chunks = [
        "// The templates of tree-sitter crates/cli/src/templates/, embedded\n"
        "// verbatim (the `include_str!` constants of init.rs). Generated by\n"
        "// tools/next/gen_init_templates.py from the pinned checkout; do not edit.\n"
    ]
    for name, file in ENTRIES:
        chunks.append(emit(name, file))
    with open(OUT, "w") as f:
        f.write("\n".join(chunks))


if __name__ == "__main__":
    main()
