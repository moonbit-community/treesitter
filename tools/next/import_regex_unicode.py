"""Generate regex_syntax/unicode_tables/*.mbt from regex-syntax 0.8.11.

Usage:
  python3 tools/next/import_regex_unicode.py [REGEX_SYNTAX_DIR]

REGEX_SYNTAX_DIR defaults to the cargo registry copy of regex-syntax 0.8.11.
Every table of `src/unicode_tables/*.rs` that the crate compiles with its
default features (Unicode 16.0.0) is converted to MoonBit data. Range tables
are stored as compact strings of hexadecimal `start-end` pairs and decoded by
`codec.mbt`; their order and contents are exactly the crate's.
Development-only; the generated files have no Python or Rust dependency.
Run `moon fmt` afterwards (the committed files are the formatted output).
"""
from pathlib import Path
import ast
import os
import re
import sys

DEFAULT = Path(os.path.expanduser(
    '~/.cargo/registry/src/index.crates.io-1949cf8c6b5b557f/regex-syntax-0.8.11'))
root = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
source = root / 'src/unicode_tables'
out_dir = Path(__file__).resolve().parents[2] / 'regex_syntax/unicode_tables'
CHAR = r"'(?:\\u\{[0-9a-fA-F]+\}|\\.|[^'\\])'"

HEADER = ('// Generated by tools/next/import_regex_unicode.py from regex-syntax 0.8.11\n'
          '// src/unicode_tables/{name}.rs (Unicode 16.0.0). Do not edit.\n')


def cp(text):
    if text.startswith("'\\u{"):
        return int(text[4:-2], 16)
    return ord(ast.literal_eval(text))


def encode_ranges(body):
    pairs = re.findall(r'\((' + CHAR + r'),\s*(' + CHAR + r')\)', body)
    parts = []
    for a, b in pairs:
        s, e = cp(a), cp(b)
        parts.append(f'{s:x}' if s == e else f'{s:x}-{e:x}')
    return ','.join(parts)


def mbt_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def consts(text):
    """Map constant name -> encoded ranges for every `(char, char)` table."""
    result = {}
    for name, body in re.findall(
            r'pub const ([A-Z_0-9]+): &\'static \[\(char, char\)\] =\s*&\[(.*?)\];',
            text, re.S):
        result[name] = encode_ranges(body)
    return result


def by_name(text):
    m = re.search(r'pub const BY_NAME:[^=]*=\s*&\[(.*?)\];', text, re.S)
    return re.findall(r'\("([^"]+)",\s*([A-Z_0-9]+)\)', m.group(1))


def write(name, body):
    (out_dir / f'{name}.mbt').write_text(HEADER.format(name=name) + body)


def gen_by_name(module):
    text = (source / f'{module}.rs').read_text()
    tables = consts(text)
    lines = [f'\n///|\n/// `{module}::BY_NAME`: (canonical name, encoded ranges), sorted by name.\n',
             f'pub let {module}_by_name : Array[(String, String)] = [\n']
    for name, const in by_name(text):
        lines.append(f'  ({mbt_string(name)}, {mbt_string(tables[const])}),\n')
    lines.append(']\n')
    write(module, ''.join(lines))


out_dir.mkdir(parents=True, exist_ok=True)
for module in ['age', 'general_category', 'grapheme_cluster_break', 'property_bool',
               'script', 'script_extension', 'sentence_break', 'word_break']:
    gen_by_name(module)

# perl_word::PERL_WORD
text = (source / 'perl_word.rs').read_text()
write('perl_word', '\n///|\n/// `perl_word::PERL_WORD`, encoded.\n'
      f'pub let perl_word : String = {mbt_string(consts(text)["PERL_WORD"])}\n')

# case_folding_simple::CASE_FOLDING_SIMPLE as `k:v.v,k:v` (hex).
text = (source / 'case_folding_simple.rs').read_text()
entries = []
for key, targets in re.findall(r'\((' + CHAR + r'),\s*&\[([^]]*)\]\)', text):
    values = '.'.join(f'{cp(t):x}' for t in re.findall(CHAR, targets))
    entries.append(f'{cp(key):x}:{values}')
write('case_folding_simple',
      '\n///|\n/// `case_folding_simple::CASE_FOLDING_SIMPLE` as `key:value.value,...`\n'
      '/// (hex code points), sorted by key.\n'
      f'pub let case_folding_simple : String = {mbt_string(",".join(entries))}\n')

# property_names::PROPERTY_NAMES
text = (source / 'property_names.rs').read_text()
pairs = re.findall(r'\("([^"]+)",\s*"([^"]+)"\)', text)
body = ['\n///|\n/// `property_names::PROPERTY_NAMES`: (normalized, canonical), sorted.\n',
        'pub let property_names : Array[(String, String)] = [\n']
body += [f'  ({mbt_string(a)}, {mbt_string(b)}),\n' for a, b in pairs]
body.append(']\n')
write('property_names', ''.join(body))

# property_values::PROPERTY_VALUES
text = (source / 'property_values.rs').read_text()
body = ['\n///|\n/// `property_values::PROPERTY_VALUES`: per canonical property name, the\n',
        '/// (normalized value, canonical value) pairs. Both levels are sorted.\n',
        'pub let property_values : Array[(String, Array[(String, String)])] = [\n']
for prop, values in re.findall(r'\(\s*"([^"]+)",\s*&\[(.*?)\],\s*\)', text, re.S):
    body.append(f'  (\n    {mbt_string(prop)},\n    [\n')
    body += [f'      ({mbt_string(a)}, {mbt_string(b)}),\n'
             for a, b in re.findall(r'\("([^"]+)",\s*"([^"]+)"\)', values)]
    body.append('    ],\n  ),\n')
body.append(']\n')
write('property_values', ''.join(body))
print(f'wrote tables to {out_dir}')
