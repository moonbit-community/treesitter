"""Freeze edited old-tree spans from the pinned C runtime (development only)."""
from pathlib import Path
import json
import random
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / '_build/edited-spans'
OUT.mkdir(parents=True, exist_ok=True)
assert subprocess.check_output(['git', '-C', str(ROOT / '.repos/tree-sitter'), 'rev-parse', 'HEAD'], text=True).strip() == '4a412a01a0147d0f50bf7e749572fa632d1ab203'
assert subprocess.check_output(['git', '-C', str(ROOT / '.repos/tree-sitter-json'), 'rev-parse', 'HEAD'], text=True).strip() == 'ee35a6ebefcef0c5c416c0d1ccec7370cfca5a24'
(OUT / 'spans.c').write_text(r'''
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "tree_sitter/api.h"
const TSLanguage *tree_sitter_json(void);
static TSPoint point(const char *s, unsigned n) {
  TSPoint p = {0, 0};
  for (unsigned i = 0; i < n; i++) {
    if (s[i] == '\n') {p.row++; p.column = 0;} else {p.column++;}
  }
  return p;
}
static void dump(TSNode n, int *first) {
  TSPoint s = ts_node_start_point(n), e = ts_node_end_point(n);
  printf("%s[\"", *first ? "" : ",");
  for (const char *c = ts_node_type(n); *c; c++) {
    if (*c == '"' || *c == '\\') putchar('\\');
    putchar(*c);
  }
  printf("\",%u,%u,%u,%u,%u,%u]", ts_node_start_byte(n), ts_node_end_byte(n), s.row, s.column, e.row, e.column);
  *first = 0;
  for (unsigned i = 0; i < ts_node_child_count(n); i++) dump(ts_node_child(n, i), first);
}
int main(int argc, char **argv) {
  if (argc != 6) return 2;
  TSParser *p = ts_parser_new(); ts_parser_set_language(p, tree_sitter_json());
  TSTree *t = ts_parser_parse_string(p, NULL, argv[1], strlen(argv[1]));
  unsigned s = atoi(argv[3]), o = atoi(argv[4]), n = atoi(argv[5]);
  TSInputEdit edit = {s, o, n, point(argv[1], s), point(argv[1], o), point(argv[2], n)};
  ts_tree_edit(t, &edit);
  int first = 1; printf("["); dump(ts_tree_root_node(t), &first); printf("]\n");
  ts_tree_delete(t); ts_parser_delete(p);
}
''')
subprocess.run(['cc', '-O2', '-I.repos/tree-sitter/lib/include', '-I.repos/tree-sitter/lib/src', '-I.repos/tree-sitter-json/src', str(OUT / 'spans.c'), '.repos/tree-sitter-json/src/parser.c', '.repos/tree-sitter/lib/src/lib.c', '-o', str(OUT / 'spans')], cwd=ROOT, check=True)
rng = random.Random(23)
cases = [('1 2 3', 1, 4, '1'), ('[1,2,3]', 1, 6, '0'), ('1\n2\n3', 1, 4, '\n4\n')]
for source in ['1 2 3', '[1,2,3]', '{"a":1,"b":[2,3]}', '1\n2\n3', '[\n1,\n2,\n3\n]']:
    for _ in range(24):
        start = rng.randrange(len(source) + 1)
        end = rng.randrange(start, len(source) + 1)
        cases.append((source, start, end, rng.choice(['', '0', '[]', '\n', '\n1\n', '  '])))
lines = ['// Generated by tools/import_edited_spans.py against the pinned C runtime.', '///|', 'test "edited old-tree byte and point spans match upstream" {', '  let parser = @ts.Parser::new(upstream_json_language())', '  let cases : Array[(String, Int, Int, String, Json)] = [']
for source, start, end, replacement in cases:
    after = source[:start] + replacement + source[end:]
    expected = json.loads(subprocess.check_output([str(OUT / 'spans'), source, after, str(start), str(end), str(start + len(replacement))], text=True))
    lines.append(f'    ({json.dumps(source)}, {start}, {end}, {json.dumps(replacement)}, {json.dumps(expected, separators=(",", ":"))}),')
lines += ['  ]', '  for (source, start, end, replacement, expected) in cases {', '    let tree = parser.parse_string(source)', '    let after = @utf8.encode(source)[:start].to_owned() + @utf8.encode(replacement) + @utf8.encode(source)[end:].to_owned()', '    let fresh = parser.parse(after)', '    let new_end = start + @utf8.encode(replacement).length()', '    tree.edit({ start_byte: start, old_end_byte: end, new_end_byte: new_end, start_point: tree.point_at(start), old_end_point: tree.point_at(end), new_end_point: fresh.point_at(new_end) })', '    let spans : Array[Json] = []', '    fn visit(node : @ts.Node) {', '      spans.push([Json(node.kind()), Json(node.start_byte()), Json(node.end_byte()), Json(node.start_position().row), Json(node.start_position().column), Json(node.end_position().row), Json(node.end_position().column)])', '      node.children().each(visit)', '    }', '    visit(tree.root_node())', '    assert_eq(Json(spans), expected, msg="\\{source} @ \\{start}..\\{end} -> \\{replacement}")', '  }', '}']
(ROOT / 'compat/edited_spans_test.mbt').write_text('\n'.join(lines) + '\n')
